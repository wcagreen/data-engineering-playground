#!/usr/bin/env python3
"""
Generate dbt/models/staging/sources.yml from CSV files in data/raw/.

Run this whenever you add or replace a CSV in data/raw/ so your dbt models
have up-to-date source column definitions.

Usage:
    python scripts/dev/generate_sources.py
    python scripts/dev/generate_sources.py --data-dir data/raw --output dbt/models/staging/sources.yml

Column names are normalized using the same PostgreSQL-safe rules as elt_dag.py
so the generated sources.yml matches the actual column names in the database.
"""

from __future__ import annotations

import argparse
import csv
import hashlib
import re
from pathlib import Path

# ── Column normalization (mirrors elt_dag.py exactly) ──────────────────────────

POSTGRES_IDENTIFIER_MAX_LEN = 63


def _postgres_safe_column_name(name: str, index: int, used_names: set[str]) -> str:
    base = re.sub(r"[^0-9A-Za-z_]+", "_", str(name)).strip("_")
    if not base:
        base = f"col_{index + 1}"
    if base[0].isdigit():
        base = f"col_{base}"

    digest = hashlib.sha1(str(name).encode("utf-8")).hexdigest()[:8]
    reserved = len(digest) + 1
    trimmed = base[: POSTGRES_IDENTIFIER_MAX_LEN - reserved]
    candidate = f"{trimmed}_{digest}"

    counter = 1
    while candidate in used_names:
        suffix = f"_{counter}"
        max_len = POSTGRES_IDENTIFIER_MAX_LEN - len(suffix)
        candidate = f"{candidate[:max_len]}{suffix}"
        counter += 1

    used_names.add(candidate)
    return candidate


def _normalize_postgres_columns(columns: list[str]) -> list[str]:
    used_names: set[str] = set()
    used_truncated_names: set[str] = set()
    normalized: list[str] = []

    for i, column in enumerate(columns):
        raw_name = str(column)
        raw_truncated = raw_name[:POSTGRES_IDENTIFIER_MAX_LEN]

        if (
            len(raw_name) <= POSTGRES_IDENTIFIER_MAX_LEN
            and raw_truncated not in used_truncated_names
        ):
            candidate = raw_name
            used_names.add(candidate)
            used_truncated_names.add(raw_truncated)
        else:
            candidate = _postgres_safe_column_name(
                name=raw_name,
                index=i,
                used_names=used_names,
            )
            while candidate[:POSTGRES_IDENTIFIER_MAX_LEN] in used_truncated_names:
                candidate = _postgres_safe_column_name(
                    name=f"{raw_name}_{i}",
                    index=i,
                    used_names=used_names,
                )
            used_truncated_names.add(candidate[:POSTGRES_IDENTIFIER_MAX_LEN])

        normalized.append(candidate)

    return normalized


# ── Table name derivation (mirrors elt_dag.py TABLE_NAME convention) ──────────

def _table_name_from_path(csv_path: Path) -> str:
    """Derive the staging table name from the CSV filename (lowercase, no extension)."""
    return re.sub(r"[^0-9a-z_]+", "_", csv_path.stem.lower()).strip("_")


# ── YAML writer (stdlib only — no PyYAML dependency) ──────────────────────────

def _build_sources_yml(tables: dict[str, list[str]], database: str, schema: str) -> str:
    lines = [
        "# Auto-generated by scripts/dev/generate_sources.py",
        "# Run 'make sources' or 'python scripts/dev/generate_sources.py' to refresh.",
        "",
        "version: 2",
        "",
        "sources:",
        f"  - name: {schema}",
        f"    database: {database}",
        f"    schema: {schema}",
        "    tables:",
    ]
    for table_name, columns in tables.items():
        lines.append(f"      - name: {table_name}")
        lines.append(f"        columns:")
        for col in columns:
            lines.append(f"          - name: {col}")
    return "\n".join(lines) + "\n"


# ── Main ──────────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--data-dir",
        type=Path,
        default=Path("data/raw"),
        help="Directory containing CSV files (default: data/raw)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("dbt/models/staging/sources.yml"),
        help="Output path for sources.yml (default: dbt/models/staging/sources.yml)",
    )
    parser.add_argument(
        "--database",
        default="playground",
        help="dbt source database name (default: playground)",
    )
    parser.add_argument(
        "--schema",
        default="staging",
        help="dbt source schema name (default: staging)",
    )
    args = parser.parse_args()

    csv_files = sorted(args.data_dir.glob("*.csv"))
    if not csv_files:
        print(f"No CSV files found in {args.data_dir}")
        return

    tables: dict[str, list[str]] = {}
    for csv_path in csv_files:
        table_name = _table_name_from_path(csv_path)
        with open(csv_path, newline="", encoding="utf-8-sig") as f:
            reader = csv.reader(f)
            raw_columns = next(reader, [])
        normalized = _normalize_postgres_columns(raw_columns)
        tables[table_name] = normalized
        print(f"  {csv_path.name}  →  staging.{table_name}  ({len(normalized)} columns)")

    content = _build_sources_yml(tables, database=args.database, schema=args.schema)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8")
    print(f"\nWrote {args.output}")


if __name__ == "__main__":
    main()
